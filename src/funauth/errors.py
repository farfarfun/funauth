"""账号域的异常。

全是 `RuntimeError` 子类，**不是 HTTP 异常** —— 这个包不依赖任何 web 框架，
状态码由调用方翻译（见 README 里 FastAPI 的例子）。异常消息是面向终端用户的
中文，可以直接当 `detail` 回给前端。
"""

from __future__ import annotations


class AuthError(RuntimeError):
    """本包所有异常的基类。调用方可以只捕这一个。"""


class BadCredentials(AuthError):
    """用户名不存在、密码不对、或账号已停用。

    三种情况**共用一条消息**，见 `Accounts.authenticate` 的说明。
    """


class UsernameTaken(AuthError):
    """用户名已被占用。"""


class InviteUnusable(AuthError):
    """邀请码不存在 / 已吊销 / 已过期 / 已用完。

    四种情况共用一条消息：分开报等于把注册接口变成「这个码存不存在」的
    探测器，攻击者能靠枚举问出哪些码是真的、只是暂时用完了。
    """


class PermissionDenied(AuthError):
    """已登录，但角色不够。"""


class AccountDisabled(AuthError):
    """凭据对，但账号被停用了。

    和 `BadCredentials` 分开是有意的：密码登录那条路**必须**把停用混进「用户名
    或密码不正确」（否则就是枚举器），但外部身份登录（微信扫码、邮箱验证码）
    没有这个顾虑 —— 能走到这一步说明对方已经证明了自己拥有那个身份，告诉他
    「你的账号被停用了」不泄漏任何他不该知道的事，而含糊其辞只会让他去反复
    重试一个永远不会成功的操作。
    """


class SignupDisabled(AuthError):
    """这个外部身份没绑过账号，而注册入口是关着的。

    和 `AccountDisabled` 一样，这件事可以直说 —— 对方拥有那个身份，而「本站
    目前不开放注册」是公开信息。
    """


class IdentityTaken(AuthError):
    """这个外部身份已经绑在**别的**账号上了。

    绑定接口可以把这个原样回给用户（他知道自己有几个账号），这不是枚举面 ——
    能触发它的前提是你已经证明了自己拥有那个外部身份。
    """


class LastLoginMethod(AuthError):
    """不能解绑：这是该账号最后一种能登进来的方式。

    解掉就变成一个谁都进不去的账号，而用户按下「解绑微信」的时候完全不会想到
    这一层。宁可拦住并提示他先设个密码。
    """


class LastAdmin(AuthError):
    """不能降级 / 停用：这是最后一个还能用的管理员。

    和 `LastLoginMethod` 是同一条哲学，只是对象从「一个账号的入口」换成了
    「整个站的后台入口」：降完就没人进得去管理页了，而点「降为访客」的人通常
    正在整理人员名单，完全不会想到这一层。补救只能去命令行或数据库 ——
    这正是宿主最不该被迫做的那种事。

    ## 为什么做进包里

    「什么算锁死」确实依赖宿主的权限模型（有的宿主还有 CLI 之类的后门入口），
    所以这条护栏可以关：每个会让「在用管理员」数量归零的方法都收一个
    `allow_last_admin`，显式传 `True` 就放行。但**默认是拦住的** —— 这个坑
    踩一次就得去命令行救场，而默认值该站在踩不到坑的那边。

    判定只看「在用的管理员」（`role == ADMIN and is_active`）：停用的管理员
    登不进来，算进去等于用一个进不去的账号给自己壮胆。

    ## 这条护栏挡不住并发

    它是「先查后写」：两个请求同时各降一个管理员，两边都会看到对方还在，于是
    都放行。和 `_insert` 的预查重不同，这里**没有任何库侧的兜底** —— 唯一约束
    拦得住重名，但拦不住「管理员数量归零」。真要硬保证得上 `SELECT ... FOR
    UPDATE` 或者库侧的部分唯一索引，那会把 SQLite 宿主排除在外，不值得。

    所以把它当成给人的护栏，不是并发保证。真撞上了，救场方式是命令行里
    `create_user(..., UserRole.ADMIN)` 或 `set_role(..., allow_last_admin=True)`。
    """


class PasswordNotSet(AuthError):
    """这个账号还没设过密码，所以没有「旧密码」可以校验。

    只有 `change_password` 会抛，而那是一条**自助**路径：调用方已经证明了自己
    就是这个账号（它是从会话里拿到用户名的）。所以这里可以直说，不像
    `authenticate` 那样必须把「没设过密码」混进「用户名或密码不正确」——
    那边的调用方是匿名的，说实话就是个账号枚举器。

    微信扫码 / 验证码注册出来的账号就是这种。正确的引导是让他走「设置密码」
    （宿主校验完会话直接调 `set_password`），而不是让他在「修改密码」表单里
    反复试自己从来没有过的旧密码。
    """


class VerificationFailed(AuthError):
    """验证码不对 / 不存在 / 已过期 / 已用过 / 试错次数超限。

    五种情况共用一条消息，和 `InviteUnusable` 同一个道理 —— 分开报就等于告诉
    爆破方「这个码存在，只是过期了」，等于把搜索空间缩小给他。
    """


class VerificationThrottled(AuthError):
    """发得太频繁了，等一会儿再来。

    这条**必须**存在：短信和邮件都是花钱的外部调用，不限频就是一个既能轰炸
    别人手机、又能刷光你账上余额的接口。
    """
